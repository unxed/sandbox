# Generator of src/tvwidth.inc: the ranges of zero-width and double-width code points.
"""Prints src/tvwidth.inc on the standard output.

The data is the Unicode Character Database of the Python standard library (unicodedata), Unicode 15.0.0
(EastAsianWidth.txt and DerivedGeneralCategory.txt). The second line of the output names the version.
The rules:
  zero width    categories Mn, Me and Cf except U+00AD, and the Hangul Jamo medial vowels and final
                consonants U+1160..U+11FF;
  double width  East Asian Width W or F (a zero-width code point stays zero-width);
  control       no entry, the unit returns -1 for them;
  all others    width 1.

Usage: gen_width.py > src/tvwidth.inc
"""
import sys
import unicodedata

LAST = 0x10FFFF


def is_zero_width(cp):
    if cp == 0x00AD:
        return False
    if 0x1160 <= cp <= 0x11FF:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def is_double_width(cp):
    if is_zero_width(cp):
        return False
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def ranges(predicate):
    """The maximal ranges (first, last) of the code points for which predicate holds."""
    result = []
    first = None
    for cp in range(LAST + 1):
        if predicate(cp):
            if first is None:
                first = cp
            last = cp
        elif first is not None:
            result.append((first, last))
            first = None
    if first is not None:
        result.append((first, last))
    return result


def table(name, items):
    """Two parallel arrays of the same length: the first and the last code point of each range."""
    lines = ["  %sCount = %d;" % (name, len(items))]
    for part, column in (("First", 0), ("Last", 1)):
        lines.append("  %s%s: array[0..%sCount - 1] of Cardinal = (" % (name, part, name))
        for n, item in enumerate(items):
            lines.append("    $%04X%s" % (item[column], "," if n + 1 < len(items) else ""))
        lines.append("  );")
    return lines


def main():
    out = ["{ Generated by tools/gen_width.py }",
           "{ Unicode version %s }" % unicodedata.unidata_version, "", "const"]
    out += table("ZeroWidth", ranges(is_zero_width))
    out.append("")
    out += table("DoubleWidth", ranges(is_double_width))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
