"""Generate udinline.asm from the TEST rows of ud.asm: every instruction stands in the code itself
(no copying into a buffer) and the variables live on another 4 KB page, so that the dynamic cores
translate the code page instead of sending it to the normal core (a page that is written is
treated as self-modifying). Usage: python3 gen_udinline.py > udinline.asm"""
import re
rows=[]
for line in open('dosbox-x-sse2/ud.asm'):
    m=re.match(r'\s*TEST\s+"([^"]*)",\s*(\d+),\s*(\w+),\s*(.*?)\s*$',line)
    if m: rows.append((m.group(1),int(m.group(2)),m.group(3),m.group(4)))
out=['; GENERATED by gen_udinline.py from the rows of ud.asm (see there).','\torg 100h','\tcpu 686','',
 '%ifdef SSE2\nFENCE equ 0\n%else\nFENCE equ 1\n%endif','%ifdef SSE2DOUBLE\nDBL equ 0\n%else\nDBL equ 1\n%endif','%ifdef SSE2INT\nIXM equ 0\n%else\nIXM equ 1\n%endif','',
 'start:','\txor ax, ax','\tmov es, ax','\tcli','\tmov word [es:6*4], ud_handler','\tmov [es:6*4+2], cs','\tsti',
 '\tmov eax, cr4','\tor ax, 600h','\tmov cr4, eax','\tjmp body','',
 'ud_handler:','\tpush bp','\tmov bp, sp','\tpush ax','\tmovzx ax, byte [cs:curlen]','\tadd [bp+2], ax','\tmov byte [cs:udflag], 1','\tpop ax','\tpop bp','\tiret','',
 '; dl = expected ud flag, dx... bx = name','report:','\tmov al, [udflag]','\tcmp al, [expect]','\tjne .fail','\tinc word [passes]','\tret','.fail:','\tinc byte [fails]','\tmov dx, s_fail','\tmov ah, 9','\tint 21h','\tmov dx, bx','\tmov ah, 9','\tint 21h','\tmov dx, s_nl','\tmov ah, 9','\tint 21h','\tret','',
 'body:']
for i,(name,ln,exp,bts) in enumerate(rows):
    out+=['\tmov byte [curlen], %d'%ln,'\tmov byte [udflag], 0','\tmov byte [expect], %s'%exp,'\tdb %s'%bts,'\tdb 0Fh, 77h','\tmov bx, n%d'%i,'\tcall report']
out+=['\tmov dx, s_passes','\tmov ah, 9','\tint 21h','\tmov ax, [passes]','\tcall printdec','\tmov dx, s_nl','\tmov ah, 9','\tint 21h',
 '\tmov dx, s_done','\tmov ah, 9','\tint 21h','\tmovzx ax, byte [fails]','\taam','\tadd ax, 3030h','\tmov bx, ax','\tmov dl, bh','\tmov ah, 2','\tint 21h','\tmov dl, bl','\tmov ah, 2','\tint 21h','\tmov dx, s_nl','\tmov ah, 9','\tint 21h',
 '\tmov al, [fails]','\tmov ah, 4Ch','\tint 21h','',
 'printdec:','\txor cx, cx','\tmov bx, 10','.l:\txor dx, dx','\tdiv bx','\tpush dx','\tinc cx','\ttest ax, ax','\tjnz .l','.p:\tpop dx','\tadd dl, 30h','\tmov ah, 2','\tint 21h','\tloop .p','\tret','',
 '; the variables and strings are on another page than the code','\ttimes 4608 db 0','']
out+=['s_passes:\tdb "PASSES=$"','s_fail:\tdb "FAIL $"','s_nl:\tdb 13, 10, "$"','s_done:\tdb "DONE fails=$"','curlen:\tdb 0','expect:\tdb 0','udflag:\tdb 0','fails:\tdb 0','passes:\tdw 0']
for i,(name,ln,exp,bts) in enumerate(rows):
    out.append('n%d:\tdb "%s$"'%(i,name))
print('\n'.join(out))
